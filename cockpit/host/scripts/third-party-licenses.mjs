// Third-party licence notices for the code bundled into the eml-cockpit package.
//
// dist/server.cjs, dist/core.cjs (esbuild) and ui/ (vite) embed code from npm packages, so their
// licence texts have to ship with the package. The runtime dependencies in package.json are not
// bundled: npm installs them with their own licence files.
//
// Input: the source files that went into the bundles. Every file under node_modules belongs to the
// package whose root is the last node_modules/<name> segment of its path. A bundled package whose
// licence is missing or not on ALLOWED fails the build, so no copyleft code enters the bundles
// unnoticed.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import * as path from 'node:path'

const ALLOWED = new Set([
  '0BSD', 'Apache-2.0', 'BlueOak-1.0.0', 'BSD-2-Clause', 'BSD-3-Clause', 'CC0-1.0', 'ISC', 'MIT', 'Unlicense',
])
const NOTICE_FILE = /^(licen[cs]e|copying|notice)([.-].*)?$/i

// The package root of a file inside node_modules, or null for a file outside it.
function packageRoot(file) {
  const parts = file.split(path.sep)
  const at = parts.lastIndexOf('node_modules')
  if (at < 0 || at + 1 >= parts.length) return null
  const depth = parts[at + 1].startsWith('@') ? 3 : 2
  return parts.slice(0, at + depth).join(path.sep)
}

// An SPDX expression is allowed when one alternative of an OR, or every part of an AND, is.
function allowed(expression) {
  const clean = expression.replace(/[()]/g, '').trim()
  if (clean.includes(' OR ')) return clean.split(' OR ').some(allowed)
  if (clean.includes(' AND ')) return clean.split(' AND ').every(allowed)
  return ALLOWED.has(clean)
}

export function writeThirdPartyLicenses(files, outFile) {
  const roots = new Set(files.map(packageRoot).filter(Boolean))
  const packages = new Map()
  const rejected = []
  for (const root of roots) {
    const pkg = JSON.parse(readFileSync(path.join(root, 'package.json'), 'utf8'))
    const license = typeof pkg.license === 'string' ? pkg.license : pkg.license?.type
    if (!license || !allowed(license)) rejected.push(`${pkg.name}@${pkg.version}: ${license ?? 'no license field'}`)
    const texts = readdirSync(root)
      .filter((name) => NOTICE_FILE.test(name))
      .sort()
      .map((name) => readFileSync(path.join(root, name), 'utf8').trim())
    packages.set(`${pkg.name}@${pkg.version}`, { name: pkg.name, version: pkg.version, license, texts })
  }
  if (rejected.length) {
    throw new Error(`bundled packages with a missing or disallowed licence:\n  ${rejected.join('\n  ')}`)
  }

  const sections = [...packages.keys()].sort().map((key) => {
    const { name, version, license, texts } = packages.get(key)
    const body = texts.length ? texts.map((text) => '```\n' + text + '\n```').join('\n\n') : `Licensed under ${license}.`
    return `## ${name} ${version}\n\nLicense: ${license}\n\n${body}`
  })
  const header = [
    '# Third-party licenses',
    '',
    'The eml-cockpit package bundles code from the following packages into dist/ and ui/.',
    'Generated by scripts/third-party-licenses.mjs at build time.',
  ].join('\n')
  writeFileSync(outFile, `${header}\n\n${sections.join('\n\n')}\n`)
  return packages.size
}
